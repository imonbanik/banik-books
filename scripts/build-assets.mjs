// Combines the CSS into one file and stamps asset links with a version, so browsers can keep
// files for a long time and still receive every release immediately.
// Run `npm run build:assets` before committing any CSS, JavaScript or asset change.
// `--check` changes nothing and fails if the committed files are out of date.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { buildCssBundle } = require("../backend/css-bundle");
const { PAGE_ROUTES } = require("../backend/page-routes");

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FRONTEND = path.join(ROOT, "frontend");
const STYLES_ENTRY = path.join(FRONTEND, "styles.css");
const BUNDLE = path.join(FRONTEND, "css", "bundle.css");
const BUNDLE_NOTICE = "/* Generated by scripts/build-assets.mjs. Edit the files imported by frontend/styles.css instead. */\n";
const VERSION_QUERY = /\?v=[0-9a-f]+/g;
const checkOnly = process.argv.includes("--check");

function filesIn(directory, extension = "") {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return filesIn(entryPath, extension);
    return entry.name.endsWith(extension) ? [entryPath] : [];
  }).sort();
}

const pages = filesIn(path.join(FRONTEND, "pages"), ".html");
const scripts = filesIn(path.join(FRONTEND, "js"), ".js");
const assets = filesIn(path.join(FRONTEND, "assets"));

function computeVersion() {
  const hash = createHash("sha256").update(buildCssBundle(STYLES_ENTRY));
  for (const file of scripts) hash.update(path.relative(FRONTEND, file)).update(fs.readFileSync(file, "utf8").replace(VERSION_QUERY, ""));
  for (const file of assets) hash.update(path.relative(FRONTEND, file)).update(fs.readFileSync(file));
  return hash.digest("hex").slice(0, 10);
}

function stampPage(html, version) {
  return html.replace(/(href|src)="\.\/((?:js|css|assets)\/[^"?#]+)(?:\?v=[0-9a-f]+)?"/g, `$1="./$2?v=${version}"`);
}

function stampModuleImports(source, version) {
  // An import without the version would load a second, permanently cached copy of the file.
  return source.replace(/((?:from|import)\s+")(\.\.?\/[^"?]+\.js)(?:\?v=[0-9a-f]+)?(")/g, `$1$2?v=${version}$3`);
}

function findProblems() {
  const problems = [];
  for (const file of pages) {
    if (fs.readFileSync(file, "utf8").includes('href="./styles.css"')) {
      problems.push(`${path.relative(ROOT, file)} links ./styles.css. Link ./css/bundle.css instead.`);
    }
  }

  const { routes } = JSON.parse(fs.readFileSync(path.join(ROOT, "vercel.json"), "utf8"));
  for (const [alias, destination] of Object.entries(PAGE_ROUTES)) {
    if (!routes.some((route) => route.src === alias && route.dest === `/frontend${destination}`)) {
      problems.push(`vercel.json needs a route from ${alias} to /frontend${destination}.`);
    }
  }
  return problems;
}

const version = computeVersion();
const expected = new Map([[BUNDLE, `${BUNDLE_NOTICE}${buildCssBundle(STYLES_ENTRY, { version })}\n`]]);
for (const file of pages) expected.set(file, stampPage(fs.readFileSync(file, "utf8"), version));
for (const file of scripts) expected.set(file, stampModuleImports(fs.readFileSync(file, "utf8"), version));

const stale = [...expected].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content);
const problems = findProblems();

if (checkOnly) {
  for (const [file] of stale) console.error(`Out of date: ${path.relative(ROOT, file)}`);
  for (const problem of problems) console.error(problem);
  if (stale.length) console.error("Run npm run build:assets and commit the result.");
  if (stale.length || problems.length) process.exit(1);
  console.log(`Assets are current at version ${version}.`);
} else {
  for (const [file, content] of stale) fs.writeFileSync(file, content);
  for (const problem of problems) console.error(problem);
  console.log(`Assets stamped with version ${version}. ${stale.length} file(s) updated.`);
  if (problems.length) process.exit(1);
}
